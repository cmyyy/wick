#!/usr/bin/env python3
"""Fail when the committed eval/report.md no longer matches a fresh run.

`report.md` is generated by `eval/reliability.py --all`. Hand-editing a generated
file is exactly the mistake this check exists to catch: it happened. A heartbeat
range was typed by hand into the generator's own output and contradicted the
table on the same page, so a reader who re-ran the command got different numbers
than the file claimed.

Ignored on purpose, because they legitimately change every run: the timestamp
line, and the sampled heartbeat range inside each measured cell. What must match
is which items exist and what each one's verdict is.

    python eval/check-report.py           # exit 0 when they agree, 1 when they do not
    python eval/check-report.py --selftest # check the parser itself, no 6-minute run
"""
from __future__ import annotations

import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COMMITTED = ROOT / "eval" / "report.md"


def verdicts(path: Path) -> dict[str, str]:
    """item -> verdict, read from the report's table.

    Column 0 is the acceptance item, column 2 the verdict. The verdict carries
    markdown emphasis on the warn row, so `**` is stripped before comparing --
    otherwise a purely cosmetic edit would read as a mismatch.
    """
    out: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 3:
            continue
        if set(cells[0]) <= {"-", " "}:       # the |---| separator row
            continue
        if cells[0] == "验收项":               # header
            continue
        out[cells[0]] = cells[2].replace("**", "").strip()
    return out


def selftest() -> int:
    """The parser is the only non-trivial logic here, so it gets the one check."""
    import tempfile as tf

    sample = """# t

| 验收项 | 实测值 | 判定 | 复现命令 |
| --- | --- | --- | --- |
| 甲 | 心跳 1.0–2.0s | ✅ 通过 | `x` |
| 乙 | 200s 一直 running | ⚠️ **已知上限** | `y` |
"""
    p = Path(tf.mkdtemp()) / "r.md"
    p.write_text(sample, encoding="utf-8")
    got = verdicts(p)
    assert list(got) == ["甲", "乙"], f"解析出的项不对: {got}"
    assert got["甲"] == "✅ 通过", got["甲"]
    assert got["乙"] == "⚠️ 已知上限", f"** 没剥干净: {got['乙']!r}"

    empty = Path(tf.mkdtemp()) / "e.md"
    empty.write_text("# 没有表格\n", encoding="utf-8")
    assert verdicts(empty) == {}, "没有表格时应返回空"
    print("check-report selftest OK：解析对、** 剥干净、无表格返回空")
    return 0


def main(argv: list[str]) -> int:
    if "--selftest" in argv:
        return selftest()

    if not COMMITTED.exists():
        print(f"没有 {COMMITTED} —— 先跑 python eval/reliability.py --all", file=sys.stderr)
        return 2

    tmp = Path(tempfile.mkdtemp()) / "report.md"
    print(f"重跑 --all 到 {tmp}（约 6 分钟）...", flush=True)
    r = subprocess.run(
        [sys.executable, "eval/reliability.py", "--all", "--report", str(tmp)],
        cwd=ROOT,
    )
    if r.returncode != 0:
        print(f"reliability.py --all 自己就失败了（exit {r.returncode}）", file=sys.stderr)
        return r.returncode

    committed, fresh = verdicts(COMMITTED), verdicts(tmp)
    if committed == fresh:
        print(f"一致：{len(fresh)} 个验收项，判定全部相同")
        return 0

    print("\n不一致 —— 提交的 report.md 不是这次跑出来的：", file=sys.stderr)
    for item in sorted(set(committed) | set(fresh)):
        if committed.get(item) != fresh.get(item):
            print(f"  {item}\n    提交里: {committed.get(item)}\n    重跑后: {fresh.get(item)}",
                  file=sys.stderr)
    print("\n修法：跑 python eval/reliability.py --all，提交它的输出。不要手改。", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
