#!/usr/bin/env python3
"""Fail when the committed eval/report.md no longer matches a fresh run.

`report.md` is generated by `eval/reliability.py --all`. Hand-editing a generated
file is the mistake this check exists to catch.

The comparison is verbatim, on the whole file, after blotting out the two things
that legitimately differ every run: the timestamp line, and the sampled heartbeat
ranges. Everything else must match to the byte -- the verdict column, the measured
numbers, and the prose. An earlier version compared only the verdict column, which
silently passed a hand-edited `deliveries=1` -> `deliveries=7` and a rewritten
conclusion; the reviewer caught that the check did not catch what it claimed to.

    python eval/check-report.py            # exit 0 agree, 1 disagree, 2 no report
    python eval/check-report.py --selftest # 1 second: the comparison itself
"""
from __future__ import annotations

import difflib
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COMMITTED = ROOT / "eval" / "report.md"

# Things that differ on every run BY DESIGN. Everything not matched here is
# compared verbatim, so a doctored number or a rewritten sentence fails.
#
# Both patterns are deliberately narrow. An earlier version masked the whole
# timestamp LINE, which also covered the provenance sentence on it ("本机实跑，
# 非 agent 自报") and the reproducibility claim beside it -- so a version saying
# the numbers could not be reproduced passed. And the range pattern matched any
# `N.N-N.Ns` shape regardless of context, which would silently swallow a future
# real measurement that happened to look like one.
_VOLATILE = (
    (re.compile(r"实测生成：\d{4}-\d{2}-\d{2} \d{2}:\d{2}"), "实测生成：<stamp>"),
    (re.compile(r"心跳年龄在 \d+\.\d+\s*[–-]\s*\d+\.\d+s"), "心跳年龄在 <range>s"),
)


def normalize(text: str) -> str:
    for pattern, replacement in _VOLATILE:
        text = pattern.sub(replacement, text)
    return text


def compare(committed: str, fresh: str) -> int:
    """0 when the two reports agree after normalization, 1 when they do not."""
    a, b = normalize(committed), normalize(fresh)
    if a == b:
        return 0
    diff = list(difflib.unified_diff(
        a.splitlines(), b.splitlines(),
        fromfile="提交的 eval/report.md", tofile="重跑的结果", lineterm=""))
    for line in diff[:40]:
        print(line, file=sys.stderr)
    if len(diff) > 40:
        print(f"... 还有 {len(diff) - 40} 行差异（共 {len(diff)} 行）", file=sys.stderr)
    return 1


def selftest() -> int:
    """The comparison is the only non-trivial logic, so it gets the one check.

    Each case is a doctoring an earlier version of this file would have let
    through -- which is why they are here and not just in a review comment.
    """
    base = """# 报告

实测生成：2026-11-24 00:40（本机实跑）

| 验收项 | 实测值 | 判定 | 复现命令 |
| --- | --- | --- | --- |
| 甲 | 心跳年龄在 2.4–22.5s 之间 | ✅ 通过 | `x` |
| 乙 | deliveries=1 条，实际发出=1 次 | ✅ 通过 | `y` |

结论：**3 分钟回收 = 0 次**。
"""
    same_but_rerun = base.replace("2026-11-24 00:40", "2026-11-25 09:12") \
                         .replace("2.4–22.5s", "1.9–22.8s")
    doctored_number = base.replace("deliveries=1 条", "deliveries=7 条")
    doctored_prose = base.replace("3 分钟回收 = 0 次", "3 分钟回收已实现")
    doctored_verdict = base.replace("| ✅ 通过 | `x` |", "| ❌ 失败 | `x` |")
    # The line that carries the timestamp also carries this report's provenance.
    # Masking the whole line used to let this through.
    doctored_claim = base.replace("（本机实跑）", "（这些数字没有一条能复现）")

    cases = [
        ("原样", base, 0),
        ("只换了时间戳和心跳区间（每次跑都会变）", same_but_rerun, 0),
        ("改了实测里的数字", doctored_number, 1),
        ("改了正文的一句话", doctored_prose, 1),
        ("改了判定", doctored_verdict, 1),
        ("改了时间戳那一行里的声明", doctored_claim, 1),
    ]
    for name, fresh, want in cases:
        got = compare(base, fresh)
        assert got == want, f"{name}: 期望 {want}，实际 {got}"
        print(f"  {'OK  ' if got == want else 'FAIL'} {name} -> {got}")
    print("check-report selftest OK：6 个用例，改写数字/正文/判定/时间戳行声明都会红")
    return 0


def main(argv: list[str]) -> int:
    if "--selftest" in argv:
        return selftest()

    if not COMMITTED.exists():
        print(f"没有 {COMMITTED} —— 先跑 python eval/reliability.py --all", file=sys.stderr)
        return 2

    tmp = Path(tempfile.mkdtemp()) / "report.md"
    print(f"重跑 --all 到 {tmp}（约 6 分钟）...", flush=True)
    r = subprocess.run(
        [sys.executable, "eval/reliability.py", "--all", "--report", str(tmp)],
        cwd=ROOT,
    )
    if r.returncode != 0:
        print(f"reliability.py --all 自己就失败了（exit {r.returncode}）——"
              f"这不是手改导致的，先查那次跑", file=sys.stderr)
        return r.returncode

    if not tmp.exists():
        print(f"reliability.py 退出 0 却没写 {tmp} —— 查那次跑", file=sys.stderr)
        return 2

    if compare(COMMITTED.read_text(encoding="utf-8"), tmp.read_text(encoding="utf-8")) == 0:
        print("一致：整份文件逐字相同（时间戳与心跳区间按设计忽略）")
        return 0

    print("\n不一致 —— 提交的 report.md 不是这次跑出来的。", file=sys.stderr)
    print("修法：跑 python eval/reliability.py --all，提交它的输出。不要手改。", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
